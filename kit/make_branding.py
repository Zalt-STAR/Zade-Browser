#!/usr/bin/env python3
"""
Generates placeholder branding for a Helium fork: an app icon, a wordmark,
a monochrome tray icon, an SVG and two Chromium vector icons.

The mark is three circles on a dark tile. It is an original placeholder so
that the fork never ships with Helium's logo; replace it with your own art
by overwriting the files this script writes (same names, same sizes).

Usage: make_branding.py <name> <output_dir> [--tile #14171F] [--accent #6FE3B4]
Requires Pillow 10.1 or newer.
"""

import argparse
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

# Mark geometry on a 256 x 256 canvas: (centre x, centre y, radius, role)
MARK = [
    (104, 150, 58, 'accent'),
    (176, 84, 30, 'light'),
    (192, 160, 16, 'accent'),
]
TILE_RADIUS = 58
LIGHT = '#F4F7F5'
MONO_GREY = '#3C4043'
FONT_CANDIDATES = [
    '/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf',
    '/usr/share/fonts/TTF/DejaVuSans-Bold.ttf',
    '/usr/share/fonts/dejavu/DejaVuSans-Bold.ttf',
    '/System/Library/Fonts/Supplemental/Arial Bold.ttf',
    'C:/Windows/Fonts/arialbd.ttf',
]
SS = 4  # supersampling factor


def mark_bounds():
    """Bounding box of the mark on the 256 canvas."""
    left = min(cx - r for cx, _, r, _ in MARK)
    top = min(cy - r for _, cy, r, _ in MARK)
    right = max(cx + r for cx, _, r, _ in MARK)
    bottom = max(cy + r for _, cy, r, _ in MARK)
    return left, top, right, bottom


def fitted_mark(size, margin):
    """The mark scaled and centred to fill a square of `size`, minus `margin`."""
    left, top, right, bottom = mark_bounds()
    scale = (size - 2 * margin) / max(right - left, bottom - top)
    off_x = (size - (right - left) * scale) / 2 - left * scale
    off_y = (size - (bottom - top) * scale) / 2 - top * scale
    return [(cx * scale + off_x, cy * scale + off_y, r * scale, role)
            for cx, cy, r, role in MARK]


def draw_circles(draw, circles, colors, factor=1.0, shift=(0, 0)):
    """Draws mark circles; `colors` maps role to fill."""
    for cx, cy, r, role in circles:
        cx, cy, r = cx * factor + shift[0], cy * factor + shift[1], r * factor
        draw.ellipse([cx - r, cy - r, cx + r, cy + r], fill=colors[role])


def tile_icon(size, tile, accent, inset_ratio=0.0):
    """Square app icon: rounded tile with the mark, optional transparent inset."""
    big = size * SS
    img = Image.new('RGBA', (big, big), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    inset = big * inset_ratio
    side = big - 2 * inset
    factor = side / 256
    draw.rounded_rectangle([inset, inset, inset + side, inset + side],
                           radius=TILE_RADIUS * factor, fill=tile)
    draw_circles(draw, MARK, {'accent': accent, 'light': LIGHT}, factor, (inset, inset))
    return img.resize((size, size), Image.LANCZOS)


def mono_icon(size, color, margin=1.5):
    """Monochrome mark on a transparent square."""
    big = size * SS
    img = Image.new('RGBA', (big, big), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    draw_circles(draw, fitted_mark(big, margin * SS), {'accent': color, 'light': color})
    return img.resize((size, size), Image.LANCZOS)


def load_font(px):
    """A bold font at roughly `px` pixels, falling back to Pillow's built-in."""
    for candidate in FONT_CANDIDATES:
        if Path(candidate).exists():
            return ImageFont.truetype(candidate, px)
    return ImageFont.load_default(size=px)


def wordmark(name, width, height, color):
    """Mark plus product name on a transparent strip (used on a few built-in pages)."""
    big_w, big_h = width * SS, height * SS
    img = Image.new('RGBA', (big_w, big_h), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)

    mark_size = big_h
    draw_circles(draw, fitted_mark(mark_size, big_h * 0.08), {'accent': color, 'light': color})

    gap = big_h * 0.22
    room = big_w - mark_size - gap
    px = int(big_h * 0.78)
    while px > 8:
        font = load_font(px)
        left, top, right, bottom = draw.textbbox((0, 0), name, font=font)
        if right - left <= room:
            break
        px -= 2
    text_y = (big_h - (bottom - top)) / 2 - top
    draw.text((mark_size + gap - left, text_y), name, font=font, fill=color)
    return img.resize((width, height), Image.LANCZOS)


def fmt(value):
    """Formats a number the way Chromium .icon files expect."""
    rounded = round(value, 2)
    if rounded == int(rounded):
        return str(int(rounded))
    return f'{rounded}f'


def hex_argb(color):
    """'#RRGGBB' -> '0xFF, 0xRR, 0xGG, 0xBB'"""
    color = color.lstrip('#')
    return ', '.join(['0xFF'] + [f'0x{color[i:i + 2].upper()}' for i in (0, 2, 4)])


ICON_HEADER = ('// Placeholder branding generated by make_branding.py.\n'
               '// Replace with your own artwork.\n\n')


def mono_vector_icon():
    """Single-colour vector icon (tinted by the browser UI)."""
    lines = [ICON_HEADER + 'CANVAS_DIMENSIONS, 56,']
    for cx, cy, r, _ in fitted_mark(56, 3):
        lines.append(f'CIRCLE, {fmt(cx)}, {fmt(cy)}, {fmt(r)},')
    lines.append('CLOSE')
    return '\n'.join(lines) + '\n'


def color_vector_icon(tile, accent):
    """Full-colour vector icon: tile plus mark."""
    colors = {'accent': accent, 'light': LIGHT}
    lines = [
        ICON_HEADER + 'CANVAS_DIMENSIONS, 256,',
        'NEW_PATH,',
        f'PATH_COLOR_ARGB, {hex_argb(tile)},',
        f'ROUND_RECT, 0, 0, 256, 256, {TILE_RADIUS},',
    ]
    for cx, cy, r, role in MARK:
        lines += [
            'NEW_PATH,',
            f'PATH_COLOR_ARGB, {hex_argb(colors[role])},',
            f'CIRCLE, {fmt(cx)}, {fmt(cy)}, {fmt(r)},',
        ]
    lines.append('CLOSE')
    return '\n'.join(lines) + '\n'


def svg_logo(tile, accent):
    """SVG version of the app icon."""
    colors = {'accent': accent, 'light': LIGHT}
    circles = ''.join(f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="{colors[role]}"/>'
                      for cx, cy, r, role in MARK)
    return ('<svg width="256" height="256" viewBox="0 0 256 256" fill="none" '
            'xmlns="http://www.w3.org/2000/svg">'
            f'<rect width="256" height="256" rx="{TILE_RADIUS}" fill="{tile}"/>'
            f'{circles}</svg>\n')


def generate(name, out_dir, tile='#14171F', accent='#6FE3B4'):
    """Writes every branding file Helium's resource lists expect."""
    out_dir = Path(out_dir)
    (out_dir / 'app_icon').mkdir(parents=True, exist_ok=True)

    tile_icon(1024, tile, accent, inset_ratio=0.1).save(out_dir / 'app_icon/raw.png')
    tile_icon(512, tile, accent, inset_ratio=0.1).save(out_dir / 'app_icon/file.png')
    wordmark(name, 140, 32, '#000000').save(out_dir / 'product_logo.png')
    wordmark(name, 280, 64, '#000000').save(out_dir / 'product_logo_200.png')
    wordmark(name, 140, 32, '#FFFFFF').save(out_dir / 'product_logo_white.png')
    wordmark(name, 280, 64, '#FFFFFF').save(out_dir / 'product_logo_white_200.png')
    mono_icon(22, MONO_GREY).save(out_dir / 'product_logo_22_mono.png')
    (out_dir / 'product_logo.svg').write_text(svg_logo(tile, accent), encoding='utf-8')
    (out_dir / 'product_logo.icon').write_text(mono_vector_icon(), encoding='utf-8')
    (out_dir / 'product_logo_color.icon').write_text(color_vector_icon(tile, accent),
                                                     encoding='utf-8')
    return sorted(p.relative_to(out_dir).as_posix() for p in out_dir.rglob('*') if p.is_file())


def main():
    """CLI entrypoint"""
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('name')
    parser.add_argument('output_dir', type=Path)
    parser.add_argument('--tile', default='#14171F')
    parser.add_argument('--accent', default='#6FE3B4')
    args = parser.parse_args()
    for written in generate(args.name, args.output_dir, args.tile, args.accent):
        print(f'wrote {written}')


if __name__ == '__main__':
    sys.exit(main())
